//! 현장 기후 프리셋 — 기상청(KMA) 1991–2020 평년값 6개 지점.
//!
//! - 월 평균 · 최고 · 최저 기온, 강수량, 평균 풍속, 상대습도: 기상자료개방포털 평년값(data.kma.go.kr, pgmNo=188).
//!   일교차 = 월평균 최고 − 최저.
//! - 강수일수(≥ 0.1 mm): 기상청 평년값을 옮긴 위키백과 기후표 (지점별 문서).
//! - 뇌전 · 안개 · 눈 일수와 보정 목표(폭풍일 · 한파일): 기상자료개방포털 지점별 연 일수의 1991–2020 평균
//!   (뇌전 pgmNo=699, 안개 706, 폭풍 708, 눈 697, 한파 733). 2017년 3월부터 뇌전은 자동 낙뢰 관측으로 바뀌었다.
//! - 강풍 사건(태풍 · 발달한 저기압): 지점별 최대 순간풍속 순위값 상위 10개(순위값 pgmNo=103)로 맞춘
//!   임계값 초과 봉우리 모델 (`weather::TyphoonClimate`). 월 가중치 = 순위값 10건의 달 분포 + 0.2.
//!
//! 광양(현장) 은 여수(168), 당진 · 평택(현장) 은 서산(129) 지점을 대신 쓴다.
//! 와이블 형상 계수 · 기온 이상치 표준편차는 `fieldcal` 이 폭풍일 · 한파일에 맞춘 값이다 (docs/site-operation.md).

use crate::weather::{Climate, MonthClimate, TyphoonClimate};

/// 기상청 관측 기준값 — 생성 날씨의 보정 목표
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct ClimateTargets {
    pub id: String,
    /// 지점 번호
    pub station: u32,
    /// 폭풍일 (일 최대 10분 평균 13.9 m/s 이상) · 한파일 (최저 −12 °C 이하) · 눈 · 안개 · 뇌전 일수 (일/년)
    pub storm_days: f64,
    pub coldwave_days: f64,
    pub snow_days: f64,
    pub fog_days: f64,
    pub thunder_days: f64,
    /// 최대 순간풍속 순위값 상위 10개 (m/s, 큰 순) 와 기록 년수
    pub record_gusts: Vec<f64>,
    pub record_years: f64,
}

#[allow(clippy::too_many_arguments)]
fn climate(
    id: &str,
    name: &str,
    station: u32,
    temp: [f64; 12],
    tmax: [f64; 12],
    tmin: [f64; 12],
    precip: [f64; 12],
    wind: [f64; 12],
    rh: [f64; 12],
    rain_days: [f64; 12],
    snow_days: [f64; 12],
    thunder: [f64; 12],
    fog: [f64; 12],
    storm: (f64, f64, [f64; 12]),
) -> Climate {
    let months = (0..12)
        .map(|m| MonthClimate {
            temp_mean_c: temp[m],
            temp_range_c: (tmax[m] - tmin[m]).max(0.0),
            wind_mean_mps: wind[m],
            precip_mm: precip[m],
            rain_days: rain_days[m],
            snow_days: snow_days[m],
            thunder_days: thunder[m],
            fog_days: fog[m],
            humidity_pct: rh[m],
        })
        .collect();
    let (per_year, beta, counts) = storm;
    Climate {
        id: id.into(),
        name: name.into(),
        source: format!("기상청 1991–2020 평년값 · 지점 {station} (data.kma.go.kr), 순위값 상위 10개로 맞춘 강풍 사건"),
        months,
        gust_factor: 1.5,
        weibull_k: 2.0,
        hourly_wind_sd: 0.25,
        alpha: 0.14,
        temp_anomaly_sd_c: 1.8,
        temp_anomaly_sd_winter_c: 3.5,
        snow_temp_c: 1.5,
        snow_flurry_prob: 0.0,
        typhoon: Some(TyphoonClimate {
            per_year,
            threshold_mps: 25.0,
            excess_scale_mps: beta,
            month_weights: counts.iter().map(|c| c + 0.2).collect(),
            duration_h: 18.0,
            source: format!("기상청 지점 {station} 최대 순간풍속 순위값 상위 10개의 굼벨 꼬리 회귀"),
        }),
    }
}

